const STAFF_PROFILE_MIGRATION_SQL = `
  CREATE TABLE IF NOT EXISTS staff_profiles (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shop_id INTEGER NOT NULL REFERENCES shops(id) ON DELETE CASCADE,
    user_id INTEGER UNIQUE REFERENCES users(id) ON DELETE SET NULL,
    employee_id TEXT NOT NULL,
    full_name TEXT NOT NULL,
    photo_url TEXT,
    phone TEXT,
    email TEXT,
    address TEXT,
    emergency_contact_name TEXT,
    emergency_contact_phone TEXT,
    designation TEXT,
    department TEXT,
    employment_type TEXT NOT NULL DEFAULT 'full_time' CHECK (employment_type IN ('full_time', 'part_time', 'contract', 'temporary')),
    joining_date DATE,
    employment_status TEXT NOT NULL DEFAULT 'active' CHECK (employment_status IN ('active', 'inactive', 'suspended', 'terminated')),
    notes TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (shop_id, employee_id)
  );
  CREATE INDEX IF NOT EXISTS idx_staff_profiles_shop_status ON staff_profiles(shop_id, employment_status);
  CREATE INDEX IF NOT EXISTS idx_staff_profiles_shop_department ON staff_profiles(shop_id, department);
  CREATE INDEX IF NOT EXISTS idx_staff_profiles_shop_designation ON staff_profiles(shop_id, designation);
  INSERT INTO staff_profiles (
    shop_id, user_id, employee_id, full_name, phone, email, employment_status, created_at, updated_at
  )
  SELECT
    u.shop_id, u.id, 'STF-' || LPAD(u.id::text, 5, '0'), u.name, u.phone, u.email,
    CASE WHEN u.status = 'blocked' THEN 'suspended' ELSE 'active' END,
    COALESCE(u.created_at, NOW()), COALESCE(u.updated_at, u.created_at, NOW())
  FROM users u
  WHERE u.shop_id IS NOT NULL
  ON CONFLICT DO NOTHING;
`;

async function ensureStaffProfileSchema(executeQuery) {
  await executeQuery(STAFF_PROFILE_MIGRATION_SQL);
}

module.exports = { STAFF_PROFILE_MIGRATION_SQL, ensureStaffProfileSchema };
