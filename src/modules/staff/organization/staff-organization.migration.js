const STAFF_ORGANIZATION_MIGRATION_SQL = `
  CREATE TABLE IF NOT EXISTS staff_departments (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shop_id INTEGER NOT NULL REFERENCES shops(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    code TEXT,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (shop_id, name)
  );
  CREATE UNIQUE INDEX IF NOT EXISTS idx_staff_departments_shop_code
    ON staff_departments(shop_id, LOWER(code)) WHERE code IS NOT NULL;

  CREATE TABLE IF NOT EXISTS staff_designations (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shop_id INTEGER NOT NULL REFERENCES shops(id) ON DELETE CASCADE,
    department_id INTEGER REFERENCES staff_departments(id) ON DELETE SET NULL,
    title TEXT NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (shop_id, title)
  );

  CREATE TABLE IF NOT EXISTS staff_locations (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shop_id INTEGER NOT NULL REFERENCES shops(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    code TEXT,
    address TEXT,
    is_primary BOOLEAN NOT NULL DEFAULT FALSE,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (shop_id, name)
  );
  CREATE UNIQUE INDEX IF NOT EXISTS idx_staff_locations_shop_code
    ON staff_locations(shop_id, LOWER(code)) WHERE code IS NOT NULL;
  CREATE UNIQUE INDEX IF NOT EXISTS idx_staff_locations_one_primary
    ON staff_locations(shop_id) WHERE is_primary = TRUE;

  CREATE TABLE IF NOT EXISTS staff_classifications (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shop_id INTEGER NOT NULL REFERENCES shops(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    code TEXT NOT NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (shop_id, name),
    UNIQUE (shop_id, code)
  );

  ALTER TABLE staff_profiles ADD COLUMN IF NOT EXISTS department_id INTEGER REFERENCES staff_departments(id) ON DELETE SET NULL;
  ALTER TABLE staff_profiles ADD COLUMN IF NOT EXISTS designation_id INTEGER REFERENCES staff_designations(id) ON DELETE SET NULL;
  ALTER TABLE staff_profiles ADD COLUMN IF NOT EXISTS manager_staff_id INTEGER REFERENCES staff_profiles(id) ON DELETE SET NULL;
  ALTER TABLE staff_profiles ADD COLUMN IF NOT EXISTS primary_location_id INTEGER REFERENCES staff_locations(id) ON DELETE SET NULL;
  ALTER TABLE staff_profiles ADD COLUMN IF NOT EXISTS classification_id INTEGER REFERENCES staff_classifications(id) ON DELETE SET NULL;
  CREATE INDEX IF NOT EXISTS idx_staff_profiles_shop_org
    ON staff_profiles(shop_id, department_id, designation_id, manager_staff_id);

  CREATE TABLE IF NOT EXISTS staff_assignment_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    staff_profile_id INTEGER NOT NULL REFERENCES staff_profiles(id) ON DELETE RESTRICT,
    from_shop_id INTEGER REFERENCES shops(id) ON DELETE SET NULL,
    to_shop_id INTEGER REFERENCES shops(id) ON DELETE SET NULL,
    from_department_id INTEGER REFERENCES staff_departments(id) ON DELETE SET NULL,
    to_department_id INTEGER REFERENCES staff_departments(id) ON DELETE SET NULL,
    from_designation_id INTEGER REFERENCES staff_designations(id) ON DELETE SET NULL,
    to_designation_id INTEGER REFERENCES staff_designations(id) ON DELETE SET NULL,
    from_manager_staff_id INTEGER REFERENCES staff_profiles(id) ON DELETE SET NULL,
    to_manager_staff_id INTEGER REFERENCES staff_profiles(id) ON DELETE SET NULL,
    from_location_id INTEGER REFERENCES staff_locations(id) ON DELETE SET NULL,
    to_location_id INTEGER REFERENCES staff_locations(id) ON DELETE SET NULL,
    from_classification_id INTEGER REFERENCES staff_classifications(id) ON DELETE SET NULL,
    to_classification_id INTEGER REFERENCES staff_classifications(id) ON DELETE SET NULL,
    event_type TEXT NOT NULL CHECK (event_type IN ('initial_assignment', 'reassignment', 'cross_shop_transfer')),
    effective_date DATE NOT NULL,
    reason TEXT,
    actor_user_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
  );
  CREATE INDEX IF NOT EXISTS idx_staff_assignment_history_profile_effective
    ON staff_assignment_history(staff_profile_id, effective_date DESC, id DESC);
  CREATE INDEX IF NOT EXISTS idx_staff_assignment_history_shops
    ON staff_assignment_history(from_shop_id, to_shop_id, effective_date DESC);

  INSERT INTO staff_departments (shop_id, name)
  SELECT DISTINCT shop_id, TRIM(department) FROM staff_profiles
  WHERE department IS NOT NULL AND TRIM(department) <> '' ON CONFLICT DO NOTHING;
  INSERT INTO staff_designations (shop_id, title)
  SELECT DISTINCT shop_id, TRIM(designation) FROM staff_profiles
  WHERE designation IS NOT NULL AND TRIM(designation) <> '' ON CONFLICT DO NOTHING;
  INSERT INTO staff_classifications (shop_id, name, code)
  SELECT DISTINCT shop_id,
    INITCAP(REPLACE(employment_type, '_', ' ')), employment_type
  FROM staff_profiles ON CONFLICT DO NOTHING;
  UPDATE staff_profiles sp SET department_id = d.id
  FROM staff_departments d
  WHERE sp.department_id IS NULL AND d.shop_id = sp.shop_id AND LOWER(d.name) = LOWER(sp.department);
  UPDATE staff_profiles sp SET designation_id = j.id
  FROM staff_designations j
  WHERE sp.designation_id IS NULL AND j.shop_id = sp.shop_id AND LOWER(j.title) = LOWER(sp.designation);
  UPDATE staff_profiles sp SET classification_id = c.id
  FROM staff_classifications c
  WHERE sp.classification_id IS NULL AND c.shop_id = sp.shop_id AND c.code = sp.employment_type;
`;

async function ensureStaffOrganizationSchema(executeQuery) {
  await executeQuery(STAFF_ORGANIZATION_MIGRATION_SQL);
}

module.exports = { STAFF_ORGANIZATION_MIGRATION_SQL, ensureStaffOrganizationSchema };
