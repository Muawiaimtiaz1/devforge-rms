const STAFF_ACCESS_MIGRATION_SQL = `
  ALTER TABLE users ADD COLUMN IF NOT EXISTS must_change_password BOOLEAN NOT NULL DEFAULT FALSE;
  ALTER TABLE users ADD COLUMN IF NOT EXISTS password_changed_at TIMESTAMPTZ;

  CREATE TABLE IF NOT EXISTS staff_access_audit (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shop_id INTEGER NOT NULL REFERENCES shops(id) ON DELETE CASCADE,
    staff_profile_id INTEGER NOT NULL REFERENCES staff_profiles(id) ON DELETE RESTRICT,
    target_user_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
    actor_user_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
    action TEXT NOT NULL,
    before_json JSONB,
    after_json JSONB,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
  );

  CREATE INDEX IF NOT EXISTS idx_staff_access_audit_profile_created
    ON staff_access_audit(staff_profile_id, created_at DESC);
  CREATE INDEX IF NOT EXISTS idx_staff_access_audit_shop_created
    ON staff_access_audit(shop_id, created_at DESC);
`;

async function ensureStaffAccessSchema(executeQuery) {
  await executeQuery(STAFF_ACCESS_MIGRATION_SQL);
}

module.exports = { STAFF_ACCESS_MIGRATION_SQL, ensureStaffAccessSchema };
