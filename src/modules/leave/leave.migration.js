const LEAVE_MIGRATION_SQL = `
  INSERT INTO permissions (key, module, action, label) VALUES
    ('leave.view', 'leave', 'view', 'view leave'),
    ('leave.request', 'leave', 'request', 'request leave'),
    ('leave.manage', 'leave', 'manage', 'manage leave'),
    ('leave.approve', 'leave', 'approve', 'approve leave')
  ON CONFLICT (key) DO UPDATE SET module = EXCLUDED.module, action = EXCLUDED.action, label = EXCLUDED.label;

  INSERT INTO role_permissions (role_id, permission_id)
  SELECT r.id, p.id FROM roles r CROSS JOIN permissions p
  WHERE r.name IN ('Restaurant Admin', 'Manager') AND p.key LIKE 'leave.%'
  ON CONFLICT DO NOTHING;
  INSERT INTO role_permissions (role_id, permission_id)
  SELECT r.id, p.id FROM roles r CROSS JOIN permissions p
  WHERE r.name IN ('Cashier','Waiter','Kitchen','Rider','Receptionist','Inventory Staff','Accountant')
    AND p.key IN ('leave.view','leave.request')
  ON CONFLICT DO NOTHING;

  CREATE TABLE IF NOT EXISTS leave_types (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shop_id INTEGER NOT NULL REFERENCES shops(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    category TEXT NOT NULL CHECK (category IN ('annual','sick','unpaid','emergency','other')),
    is_paid BOOLEAN NOT NULL DEFAULT TRUE,
    requires_balance BOOLEAN NOT NULL DEFAULT TRUE,
    allow_half_day BOOLEAN NOT NULL DEFAULT TRUE,
    annual_entitlement_days NUMERIC(8,2) NOT NULL DEFAULT 0 CHECK (annual_entitlement_days >= 0),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (shop_id, name)
  );
  CREATE INDEX IF NOT EXISTS idx_leave_types_shop_active ON leave_types(shop_id, is_active, category);

  CREATE TABLE IF NOT EXISTS leave_balance_periods (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shop_id INTEGER NOT NULL REFERENCES shops(id) ON DELETE RESTRICT,
    staff_profile_id INTEGER NOT NULL REFERENCES staff_profiles(id) ON DELETE RESTRICT,
    leave_type_id INTEGER NOT NULL REFERENCES leave_types(id) ON DELETE RESTRICT,
    period_start DATE NOT NULL,
    period_end DATE NOT NULL,
    opening_days NUMERIC(8,2) NOT NULL DEFAULT 0 CHECK (opening_days >= 0),
    created_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CHECK (period_end >= period_start),
    UNIQUE (shop_id, staff_profile_id, leave_type_id, period_start, period_end)
  );
  CREATE INDEX IF NOT EXISTS idx_leave_balance_periods_lookup ON leave_balance_periods(shop_id, staff_profile_id, leave_type_id, period_start, period_end);

  CREATE TABLE IF NOT EXISTS leave_requests (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shop_id INTEGER NOT NULL REFERENCES shops(id) ON DELETE RESTRICT,
    staff_profile_id INTEGER NOT NULL REFERENCES staff_profiles(id) ON DELETE RESTRICT,
    leave_type_id INTEGER NOT NULL REFERENCES leave_types(id) ON DELETE RESTRICT,
    start_date DATE NOT NULL,
    end_date DATE NOT NULL,
    day_part TEXT NOT NULL DEFAULT 'full_day' CHECK (day_part IN ('full_day','first_half','second_half')),
    requested_days NUMERIC(8,2) NOT NULL CHECK (requested_days > 0),
    reason TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','approved','rejected','cancelled')),
    requested_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
    requested_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    decided_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
    decided_at TIMESTAMPTZ,
    decision_note TEXT,
    CHECK (end_date >= start_date),
    CHECK (day_part = 'full_day' OR start_date = end_date)
  );
  CREATE INDEX IF NOT EXISTS idx_leave_requests_shop_status ON leave_requests(shop_id, status, requested_at DESC);
  CREATE INDEX IF NOT EXISTS idx_leave_requests_staff_dates ON leave_requests(shop_id, staff_profile_id, start_date, end_date);

  CREATE TABLE IF NOT EXISTS leave_approval_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shop_id INTEGER NOT NULL REFERENCES shops(id) ON DELETE RESTRICT,
    leave_request_id BIGINT NOT NULL REFERENCES leave_requests(id) ON DELETE RESTRICT,
    from_status TEXT,
    to_status TEXT NOT NULL CHECK (to_status IN ('pending','approved','rejected','cancelled')),
    actor_user_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
    note TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
  );
  CREATE INDEX IF NOT EXISTS idx_leave_history_request ON leave_approval_history(leave_request_id, created_at, id);

  CREATE TABLE IF NOT EXISTS leave_balance_ledger (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shop_id INTEGER NOT NULL REFERENCES shops(id) ON DELETE RESTRICT,
    balance_period_id BIGINT NOT NULL REFERENCES leave_balance_periods(id) ON DELETE RESTRICT,
    leave_request_id BIGINT REFERENCES leave_requests(id) ON DELETE RESTRICT,
    entry_type TEXT NOT NULL CHECK (entry_type IN ('allocation','adjustment','leave_debit','reversal')),
    days NUMERIC(8,2) NOT NULL CHECK (days <> 0),
    reason TEXT NOT NULL,
    actor_user_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (leave_request_id, entry_type)
  );
  CREATE INDEX IF NOT EXISTS idx_leave_ledger_period ON leave_balance_ledger(balance_period_id, created_at, id);
  CREATE OR REPLACE FUNCTION reject_leave_balance_ledger_mutation() RETURNS TRIGGER AS $$
  BEGIN RAISE EXCEPTION 'leave_balance_ledger entries are immutable'; END;
  $$ LANGUAGE plpgsql;
  DROP TRIGGER IF EXISTS trg_leave_balance_ledger_immutable ON leave_balance_ledger;
  CREATE TRIGGER trg_leave_balance_ledger_immutable BEFORE UPDATE OR DELETE ON leave_balance_ledger
    FOR EACH ROW EXECUTE FUNCTION reject_leave_balance_ledger_mutation();

  INSERT INTO leave_types (shop_id, name, category, is_paid, requires_balance, allow_half_day, annual_entitlement_days)
  SELECT s.id, defaults.name, defaults.category, defaults.is_paid, defaults.requires_balance, TRUE, 0
  FROM shops s CROSS JOIN (VALUES
    ('Annual leave','annual',TRUE,TRUE), ('Sick leave','sick',TRUE,TRUE),
    ('Unpaid leave','unpaid',FALSE,FALSE), ('Emergency leave','emergency',TRUE,TRUE),
    ('Other leave','other',TRUE,TRUE)
  ) AS defaults(name, category, is_paid, requires_balance)
  ON CONFLICT (shop_id, name) DO NOTHING;
`;
async function ensureLeaveSchema(executeQuery) { await executeQuery(LEAVE_MIGRATION_SQL); }
module.exports = { LEAVE_MIGRATION_SQL, ensureLeaveSchema };
