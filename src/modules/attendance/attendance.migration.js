const ATTENDANCE_MIGRATION_SQL = `
  INSERT INTO permissions (key, module, action, label) VALUES
    ('attendance.view', 'attendance', 'view', 'view attendance'),
    ('attendance.clock', 'attendance', 'clock', 'clock attendance'),
    ('attendance.manage_schedules', 'attendance', 'manage_schedules', 'manage schedules attendance'),
    ('attendance.correct', 'attendance', 'correct', 'correct attendance'),
    ('attendance.approve', 'attendance', 'approve', 'approve attendance'),
    ('attendance.mark_daily', 'attendance', 'mark_daily', 'submit shift attendance')
  ON CONFLICT (key) DO UPDATE SET module = EXCLUDED.module, action = EXCLUDED.action, label = EXCLUDED.label;

  INSERT INTO role_permissions (role_id, permission_id)
  SELECT r.id, p.id FROM roles r CROSS JOIN permissions p
  WHERE r.name IN ('Restaurant Admin', 'Manager') AND p.key LIKE 'attendance.%'
  ON CONFLICT DO NOTHING;
  INSERT INTO role_permissions (role_id, permission_id)
  SELECT r.id, p.id FROM roles r CROSS JOIN permissions p
  WHERE r.name IN ('Cashier', 'Waiter', 'Kitchen', 'Rider', 'Receptionist', 'Inventory Staff', 'Accountant')
    AND p.key IN ('attendance.view', 'attendance.clock', 'attendance.correct')
  ON CONFLICT DO NOTHING;

  CREATE TABLE IF NOT EXISTS attendance_settings (
    shop_id INTEGER PRIMARY KEY REFERENCES shops(id) ON DELETE CASCADE,
    timezone TEXT NOT NULL DEFAULT 'Asia/Karachi',
    default_grace_minutes INTEGER NOT NULL DEFAULT 10 CHECK (default_grace_minutes BETWEEN 0 AND 180),
    early_departure_grace_minutes INTEGER NOT NULL DEFAULT 5 CHECK (early_departure_grace_minutes BETWEEN 0 AND 180),
    max_shift_hours INTEGER NOT NULL DEFAULT 18 CHECK (max_shift_hours BETWEEN 1 AND 24),
    updated_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
  );

  CREATE TABLE IF NOT EXISTS attendance_shift_templates (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shop_id INTEGER NOT NULL REFERENCES shops(id) ON DELETE CASCADE,
    name TEXT NOT NULL,
    start_time TIME NOT NULL,
    end_time TIME NOT NULL,
    is_overnight BOOLEAN NOT NULL DEFAULT FALSE,
    unpaid_break_minutes INTEGER NOT NULL DEFAULT 0 CHECK (unpaid_break_minutes BETWEEN 0 AND 720),
    grace_minutes INTEGER CHECK (grace_minutes BETWEEN 0 AND 180),
    version INTEGER NOT NULL DEFAULT 1,
    supersedes_id INTEGER REFERENCES attendance_shift_templates(id) ON DELETE SET NULL,
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (shop_id, name, version)
  );
  CREATE INDEX IF NOT EXISTS idx_attendance_templates_shop_active ON attendance_shift_templates(shop_id, is_active, name);

  CREATE TABLE IF NOT EXISTS attendance_weekly_schedules (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shop_id INTEGER NOT NULL REFERENCES shops(id) ON DELETE CASCADE,
    staff_profile_id INTEGER NOT NULL REFERENCES staff_profiles(id) ON DELETE RESTRICT,
    weekday SMALLINT NOT NULL CHECK (weekday BETWEEN 0 AND 6),
    shift_template_id INTEGER REFERENCES attendance_shift_templates(id) ON DELETE RESTRICT,
    is_day_off BOOLEAN NOT NULL DEFAULT FALSE,
    effective_from DATE NOT NULL,
    effective_to DATE,
    created_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CHECK ((is_day_off = TRUE AND shift_template_id IS NULL) OR (is_day_off = FALSE AND shift_template_id IS NOT NULL)),
    CHECK (effective_to IS NULL OR effective_to >= effective_from),
    UNIQUE (shop_id, staff_profile_id, weekday, effective_from)
  );
  CREATE INDEX IF NOT EXISTS idx_attendance_schedules_staff_dates ON attendance_weekly_schedules(shop_id, staff_profile_id, effective_from, effective_to);

  CREATE TABLE IF NOT EXISTS attendance_holidays (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shop_id INTEGER NOT NULL REFERENCES shops(id) ON DELETE CASCADE,
    holiday_date DATE NOT NULL,
    name TEXT NOT NULL,
    is_paid BOOLEAN NOT NULL DEFAULT TRUE,
    created_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (shop_id, holiday_date)
  );

  CREATE TABLE IF NOT EXISTS attendance_clock_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shop_id INTEGER NOT NULL REFERENCES shops(id) ON DELETE RESTRICT,
    staff_profile_id INTEGER NOT NULL REFERENCES staff_profiles(id) ON DELETE RESTRICT,
    event_type TEXT NOT NULL CHECK (event_type IN ('clock_in','break_start','break_end','clock_out')),
    occurred_at TIMESTAMPTZ NOT NULL,
    business_date DATE NOT NULL,
    source_type TEXT NOT NULL CHECK (source_type IN ('web','device','register')),
    device_id TEXT,
    register_shift_id INTEGER REFERENCES shifts(id) ON DELETE SET NULL,
    actor_user_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
    idempotency_key TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (shop_id, idempotency_key)
  );
  CREATE INDEX IF NOT EXISTS idx_attendance_events_staff_time ON attendance_clock_events(shop_id, staff_profile_id, occurred_at DESC);
  CREATE INDEX IF NOT EXISTS idx_attendance_events_shop_date ON attendance_clock_events(shop_id, business_date, staff_profile_id);
  CREATE OR REPLACE FUNCTION reject_attendance_clock_event_mutation() RETURNS TRIGGER AS $$
  BEGIN RAISE EXCEPTION 'attendance_clock_events are immutable'; END;
  $$ LANGUAGE plpgsql;
  DROP TRIGGER IF EXISTS trg_attendance_clock_events_immutable ON attendance_clock_events;
  CREATE TRIGGER trg_attendance_clock_events_immutable BEFORE UPDATE OR DELETE ON attendance_clock_events
    FOR EACH ROW EXECUTE FUNCTION reject_attendance_clock_event_mutation();

  CREATE TABLE IF NOT EXISTS attendance_corrections (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shop_id INTEGER NOT NULL REFERENCES shops(id) ON DELETE RESTRICT,
    staff_profile_id INTEGER NOT NULL REFERENCES staff_profiles(id) ON DELETE RESTRICT,
    business_date DATE NOT NULL,
    correction_type TEXT NOT NULL CHECK (correction_type IN ('add_event','replace_event','classify_absence')),
    raw_event_id BIGINT REFERENCES attendance_clock_events(id) ON DELETE RESTRICT,
    proposed_event_type TEXT CHECK (proposed_event_type IN ('clock_in','break_start','break_end','clock_out')),
    proposed_occurred_at TIMESTAMPTZ,
    proposed_absence_type TEXT CHECK (proposed_absence_type IN ('authorized','unauthorized','sick','other')),
    reason TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','approved','rejected')),
    requested_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
    requested_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    reviewed_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
    reviewed_at TIMESTAMPTZ,
    review_note TEXT,
    CHECK (correction_type <> 'replace_event' OR raw_event_id IS NOT NULL),
    CHECK (correction_type = 'classify_absence' OR (proposed_event_type IS NOT NULL AND proposed_occurred_at IS NOT NULL)),
    CHECK (correction_type <> 'classify_absence' OR proposed_absence_type IS NOT NULL)
  );
  CREATE INDEX IF NOT EXISTS idx_attendance_corrections_shop_status ON attendance_corrections(shop_id, status, requested_at DESC);
  CREATE INDEX IF NOT EXISTS idx_attendance_corrections_staff_date ON attendance_corrections(shop_id, staff_profile_id, business_date);

  CREATE TABLE IF NOT EXISTS attendance_adjustments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shop_id INTEGER NOT NULL REFERENCES shops(id) ON DELETE RESTRICT,
    staff_profile_id INTEGER NOT NULL REFERENCES staff_profiles(id) ON DELETE RESTRICT,
    correction_id BIGINT NOT NULL UNIQUE REFERENCES attendance_corrections(id) ON DELETE RESTRICT,
    business_date DATE NOT NULL,
    adjustment_type TEXT NOT NULL CHECK (adjustment_type IN ('add_event','replace_event','classify_absence')),
    raw_event_id BIGINT REFERENCES attendance_clock_events(id) ON DELETE RESTRICT,
    effective_event_type TEXT,
    effective_occurred_at TIMESTAMPTZ,
    absence_type TEXT,
    approved_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
  );
  CREATE INDEX IF NOT EXISTS idx_attendance_adjustments_staff_date ON attendance_adjustments(shop_id, staff_profile_id, business_date);

  CREATE TABLE IF NOT EXISTS attendance_daily_marks (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shop_id INTEGER NOT NULL REFERENCES shops(id) ON DELETE RESTRICT,
    staff_profile_id INTEGER NOT NULL REFERENCES staff_profiles(id) ON DELETE RESTRICT,
    business_date DATE NOT NULL,
    attendance_status TEXT NOT NULL CHECK (attendance_status IN ('present','absent','paid_leave','unpaid_leave','holiday','day_off')),
    reason TEXT NOT NULL,
    supersedes_id BIGINT REFERENCES attendance_daily_marks(id) ON DELETE RESTRICT,
    marked_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
    idempotency_key TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE(shop_id,idempotency_key)
  );
  CREATE INDEX IF NOT EXISTS idx_attendance_daily_marks_lookup ON attendance_daily_marks(shop_id,business_date,staff_profile_id,id DESC);
  CREATE OR REPLACE FUNCTION reject_attendance_daily_mark_mutation() RETURNS TRIGGER AS $$
  BEGIN RAISE EXCEPTION 'attendance_daily_marks are append-only'; END;
  $$ LANGUAGE plpgsql;
  DROP TRIGGER IF EXISTS trg_attendance_daily_marks_immutable ON attendance_daily_marks;
  CREATE TRIGGER trg_attendance_daily_marks_immutable BEFORE UPDATE OR DELETE ON attendance_daily_marks
    FOR EACH ROW EXECUTE FUNCTION reject_attendance_daily_mark_mutation();

  CREATE TABLE IF NOT EXISTS attendance_shift_registers (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shop_id INTEGER NOT NULL REFERENCES shops(id) ON DELETE RESTRICT,
    business_date DATE NOT NULL,
    shift_template_id INTEGER NOT NULL REFERENCES attendance_shift_templates(id) ON DELETE RESTRICT,
    reason TEXT NOT NULL,
    submitted_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
    submitted_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE (shop_id, business_date, shift_template_id)
  );
  CREATE INDEX IF NOT EXISTS idx_attendance_shift_registers_lookup
    ON attendance_shift_registers(shop_id, business_date DESC, shift_template_id);
  ALTER TABLE attendance_daily_marks
    ADD COLUMN IF NOT EXISTS shift_register_id BIGINT REFERENCES attendance_shift_registers(id) ON DELETE RESTRICT;
  ALTER TABLE attendance_clock_events
    ADD COLUMN IF NOT EXISTS attendance_shift_register_id BIGINT REFERENCES attendance_shift_registers(id) ON DELETE RESTRICT;
  CREATE UNIQUE INDEX IF NOT EXISTS uq_attendance_shift_clock_event
    ON attendance_clock_events(attendance_shift_register_id, staff_profile_id, event_type)
    WHERE attendance_shift_register_id IS NOT NULL;
  CREATE INDEX IF NOT EXISTS idx_attendance_shift_clock_lookup
    ON attendance_clock_events(shop_id, attendance_shift_register_id, staff_profile_id, occurred_at);
  DROP INDEX IF EXISTS uq_attendance_shift_register_staff;
  DROP INDEX IF EXISTS uq_attendance_shift_mark_staff_date;
  CREATE INDEX IF NOT EXISTS idx_attendance_shift_mark_history
    ON attendance_daily_marks(shop_id, business_date, staff_profile_id, id DESC)
    WHERE shift_register_id IS NOT NULL;
  CREATE OR REPLACE FUNCTION reject_attendance_shift_register_mutation() RETURNS TRIGGER AS $$
  BEGIN RAISE EXCEPTION 'attendance_shift_registers are immutable'; END;
  $$ LANGUAGE plpgsql;
  DROP TRIGGER IF EXISTS trg_attendance_shift_registers_immutable ON attendance_shift_registers;
  CREATE TRIGGER trg_attendance_shift_registers_immutable BEFORE UPDATE OR DELETE ON attendance_shift_registers
    FOR EACH ROW EXECUTE FUNCTION reject_attendance_shift_register_mutation();

  CREATE TABLE IF NOT EXISTS attendance_summary_snapshots (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shop_id INTEGER NOT NULL REFERENCES shops(id) ON DELETE RESTRICT,
    period_start DATE NOT NULL,
    period_end DATE NOT NULL,
    timezone TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'draft' CHECK (status IN ('draft','approved')),
    input_version TEXT NOT NULL,
    created_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    approved_by INTEGER REFERENCES users(id) ON DELETE SET NULL,
    approved_at TIMESTAMPTZ,
    CHECK (period_end >= period_start),
    UNIQUE (shop_id, period_start, period_end, input_version)
  );
  CREATE INDEX IF NOT EXISTS idx_attendance_snapshots_shop_period ON attendance_summary_snapshots(shop_id, status, period_start DESC, period_end DESC);

  CREATE TABLE IF NOT EXISTS attendance_summary_snapshot_rows (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    snapshot_id BIGINT NOT NULL REFERENCES attendance_summary_snapshots(id) ON DELETE RESTRICT,
    shop_id INTEGER NOT NULL REFERENCES shops(id) ON DELETE RESTRICT,
    staff_profile_id INTEGER NOT NULL REFERENCES staff_profiles(id) ON DELETE RESTRICT,
    scheduled_days INTEGER NOT NULL DEFAULT 0,
    present_days NUMERIC(8,2) NOT NULL DEFAULT 0,
    paid_leave_days NUMERIC(8,2) NOT NULL DEFAULT 0,
    paid_full_leave_days NUMERIC(8,2) NOT NULL DEFAULT 0,
    paid_half_leave_count INTEGER NOT NULL DEFAULT 0,
    unpaid_leave_days NUMERIC(8,2) NOT NULL DEFAULT 0,
    absent_days NUMERIC(8,2) NOT NULL DEFAULT 0,
    work_minutes INTEGER NOT NULL DEFAULT 0,
    overtime_minutes INTEGER NOT NULL DEFAULT 0,
    late_minutes INTEGER NOT NULL DEFAULT 0,
    early_departure_minutes INTEGER NOT NULL DEFAULT 0,
    missing_clock_days INTEGER NOT NULL DEFAULT 0,
    detail_json JSONB NOT NULL DEFAULT '[]'::jsonb,
    UNIQUE (snapshot_id, staff_profile_id)
  );
  CREATE INDEX IF NOT EXISTS idx_attendance_snapshot_rows_staff ON attendance_summary_snapshot_rows(shop_id, staff_profile_id, snapshot_id);
  ALTER TABLE attendance_summary_snapshot_rows ADD COLUMN IF NOT EXISTS paid_full_leave_days NUMERIC(8,2) NOT NULL DEFAULT 0;
  ALTER TABLE attendance_summary_snapshot_rows ADD COLUMN IF NOT EXISTS paid_half_leave_count INTEGER NOT NULL DEFAULT 0;

  CREATE OR REPLACE FUNCTION reject_approved_attendance_snapshot_mutation() RETURNS TRIGGER AS $$
  BEGIN
    IF (TG_OP = 'DELETE' AND OLD.status = 'approved') OR (TG_OP = 'UPDATE' AND OLD.status = 'approved') THEN
      RAISE EXCEPTION 'approved attendance snapshots are immutable';
    END IF;
    RETURN CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NEW END;
  END;
  $$ LANGUAGE plpgsql;
  DROP TRIGGER IF EXISTS trg_attendance_snapshot_immutable ON attendance_summary_snapshots;
  CREATE TRIGGER trg_attendance_snapshot_immutable BEFORE UPDATE OR DELETE ON attendance_summary_snapshots
    FOR EACH ROW EXECUTE FUNCTION reject_approved_attendance_snapshot_mutation();

  CREATE OR REPLACE FUNCTION reject_approved_attendance_snapshot_row_mutation() RETURNS TRIGGER AS $$
  BEGIN
    IF EXISTS (SELECT 1 FROM attendance_summary_snapshots s WHERE s.id = OLD.snapshot_id AND s.status = 'approved') THEN
      RAISE EXCEPTION 'approved attendance snapshot rows are immutable';
    END IF;
    RETURN CASE WHEN TG_OP = 'DELETE' THEN OLD ELSE NEW END;
  END;
  $$ LANGUAGE plpgsql;
  DROP TRIGGER IF EXISTS trg_attendance_snapshot_rows_immutable ON attendance_summary_snapshot_rows;
  CREATE TRIGGER trg_attendance_snapshot_rows_immutable BEFORE UPDATE OR DELETE ON attendance_summary_snapshot_rows
    FOR EACH ROW EXECUTE FUNCTION reject_approved_attendance_snapshot_row_mutation();
`;

async function ensureAttendanceSchema(executeQuery) { await executeQuery(ATTENDANCE_MIGRATION_SQL); }
module.exports = { ATTENDANCE_MIGRATION_SQL, ensureAttendanceSchema };
