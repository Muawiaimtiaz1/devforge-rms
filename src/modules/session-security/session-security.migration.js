const SESSION_SECURITY_MIGRATION_SQL = `
  CREATE TABLE IF NOT EXISTS session_devices (
    sid TEXT PRIMARY KEY,
    device_id TEXT NOT NULL UNIQUE,
    user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    shop_id INTEGER REFERENCES shops(id) ON DELETE CASCADE,
    user_agent TEXT,
    ip_address TEXT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    last_seen_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    revoked_at TIMESTAMPTZ,
    revoked_reason TEXT
  );
  ALTER TABLE session_devices ADD COLUMN IF NOT EXISTS device_id TEXT;
  UPDATE session_devices SET device_id = MD5(sid) WHERE device_id IS NULL;
  ALTER TABLE session_devices ALTER COLUMN device_id SET NOT NULL;
  CREATE UNIQUE INDEX IF NOT EXISTS idx_session_devices_device_id
    ON session_devices(device_id);
  CREATE INDEX IF NOT EXISTS idx_session_devices_user_active
    ON session_devices(user_id, revoked_at, last_seen_at DESC);

  CREATE TABLE IF NOT EXISTS security_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shop_id INTEGER REFERENCES shops(id) ON DELETE SET NULL,
    user_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
    actor_user_id INTEGER REFERENCES users(id) ON DELETE SET NULL,
    event_type TEXT NOT NULL,
    session_sid TEXT,
    ip_address TEXT,
    user_agent TEXT,
    details_json JSONB,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
  );
  CREATE INDEX IF NOT EXISTS idx_security_events_user_created
    ON security_events(user_id, created_at DESC);
  CREATE INDEX IF NOT EXISTS idx_security_events_shop_created
    ON security_events(shop_id, created_at DESC);
`;

async function ensureSessionSecuritySchema(executeQuery) {
  await executeQuery(SESSION_SECURITY_MIGRATION_SQL);
}

module.exports = { SESSION_SECURITY_MIGRATION_SQL, ensureSessionSecuritySchema };
