const PAYROLL_MIGRATION_SQL = `
  INSERT INTO permissions (key, module, action, label) VALUES
    ('payroll.view','payroll','view','view payroll'), ('payroll.configure','payroll','configure','configure payroll'),
    ('payroll.run','payroll','run','run payroll'), ('payroll.review','payroll','review','review payroll'),
    ('payroll.approve','payroll','approve','approve payroll'), ('payroll.finalize','payroll','finalize','finalize payroll')
  ON CONFLICT (key) DO UPDATE SET module=EXCLUDED.module, action=EXCLUDED.action, label=EXCLUDED.label;
  INSERT INTO role_permissions (role_id, permission_id)
  SELECT r.id,p.id FROM roles r CROSS JOIN permissions p WHERE r.name IN ('Restaurant Admin','Accountant') AND p.key LIKE 'payroll.%'
  ON CONFLICT DO NOTHING;
  INSERT INTO role_permissions (role_id, permission_id)
  SELECT r.id,p.id FROM roles r CROSS JOIN permissions p WHERE r.name='Manager' AND p.key IN ('payroll.view','payroll.run','payroll.review')
  ON CONFLICT DO NOTHING;

  CREATE TABLE IF NOT EXISTS payroll_salary_configs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, shop_id INTEGER NOT NULL REFERENCES shops(id) ON DELETE RESTRICT,
    staff_profile_id INTEGER NOT NULL REFERENCES staff_profiles(id) ON DELETE RESTRICT,
    compensation_type TEXT NOT NULL CHECK (compensation_type IN ('monthly','hourly')), currency CHAR(3) NOT NULL DEFAULT 'PKR',
    base_amount NUMERIC(14,2) NOT NULL CHECK (base_amount >= 0), effective_from DATE NOT NULL, effective_to DATE,
    standard_monthly_minutes INTEGER CHECK (standard_monthly_minutes > 0), overtime_enabled BOOLEAN NOT NULL DEFAULT FALSE,
    overtime_multiplier NUMERIC(6,3) NOT NULL DEFAULT 1.500 CHECK (overtime_multiplier >= 1),
    monthly_unpaid_absence_policy TEXT NOT NULL DEFAULT 'prorate_scheduled_days' CHECK (monthly_unpaid_absence_policy IN ('none','prorate_scheduled_days')),
    paid_full_leave_allowance INTEGER NOT NULL DEFAULT 0 CHECK (paid_full_leave_allowance BETWEEN 0 AND 366),
    paid_half_leave_allowance INTEGER NOT NULL DEFAULT 0 CHECK (paid_half_leave_allowance BETWEEN 0 AND 732),
    deduct_excess_paid_leave BOOLEAN NOT NULL DEFAULT TRUE,
    change_reason TEXT NOT NULL DEFAULT 'Salary configuration',
    created_by INTEGER REFERENCES users(id) ON DELETE SET NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CHECK (effective_to IS NULL OR effective_to >= effective_from), UNIQUE(shop_id,staff_profile_id,effective_from)
  );
  CREATE INDEX IF NOT EXISTS idx_payroll_salary_effective ON payroll_salary_configs(shop_id,staff_profile_id,effective_from DESC,effective_to);
  ALTER TABLE payroll_salary_configs ADD COLUMN IF NOT EXISTS paid_full_leave_allowance INTEGER NOT NULL DEFAULT 0;
  ALTER TABLE payroll_salary_configs ADD COLUMN IF NOT EXISTS paid_half_leave_allowance INTEGER NOT NULL DEFAULT 0;
  ALTER TABLE payroll_salary_configs ADD COLUMN IF NOT EXISTS deduct_excess_paid_leave BOOLEAN NOT NULL DEFAULT TRUE;
  ALTER TABLE payroll_salary_configs ADD COLUMN IF NOT EXISTS change_reason TEXT NOT NULL DEFAULT 'Salary configuration';
  DO $$ BEGIN
    ALTER TABLE payroll_salary_configs ADD CONSTRAINT payroll_salary_full_leave_allowance_check CHECK (paid_full_leave_allowance BETWEEN 0 AND 366);
  EXCEPTION WHEN duplicate_object THEN NULL; END $$;
  DO $$ BEGIN
    ALTER TABLE payroll_salary_configs ADD CONSTRAINT payroll_salary_half_leave_allowance_check CHECK (paid_half_leave_allowance BETWEEN 0 AND 732);
  EXCEPTION WHEN duplicate_object THEN NULL; END $$;

  CREATE TABLE IF NOT EXISTS payroll_recurring_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, shop_id INTEGER NOT NULL REFERENCES shops(id) ON DELETE RESTRICT,
    staff_profile_id INTEGER NOT NULL REFERENCES staff_profiles(id) ON DELETE RESTRICT,
    item_type TEXT NOT NULL CHECK (item_type IN ('allowance','deduction')), name TEXT NOT NULL, amount NUMERIC(14,2) NOT NULL CHECK(amount >= 0),
    effective_from DATE NOT NULL, effective_to DATE, created_by INTEGER REFERENCES users(id) ON DELETE SET NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CHECK (effective_to IS NULL OR effective_to >= effective_from)
  );
  CREATE INDEX IF NOT EXISTS idx_payroll_items_effective ON payroll_recurring_items(shop_id,staff_profile_id,effective_from,effective_to);

  CREATE TABLE IF NOT EXISTS payroll_advances (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, shop_id INTEGER NOT NULL REFERENCES shops(id) ON DELETE RESTRICT,
    staff_profile_id INTEGER NOT NULL REFERENCES staff_profiles(id) ON DELETE RESTRICT, currency CHAR(3) NOT NULL DEFAULT 'PKR',
    principal_amount NUMERIC(14,2) NOT NULL CHECK(principal_amount > 0), installment_amount NUMERIC(14,2) NOT NULL CHECK(installment_amount > 0),
    issued_on DATE NOT NULL, note TEXT NOT NULL, status TEXT NOT NULL DEFAULT 'active' CHECK(status IN ('active','settled','cancelled')),
    created_by INTEGER REFERENCES users(id) ON DELETE SET NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
  );
  CREATE INDEX IF NOT EXISTS idx_payroll_advances_staff ON payroll_advances(shop_id,staff_profile_id,status,issued_on);
  CREATE TABLE IF NOT EXISTS payroll_advance_ledger (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, shop_id INTEGER NOT NULL REFERENCES shops(id) ON DELETE RESTRICT,
    advance_id BIGINT NOT NULL REFERENCES payroll_advances(id) ON DELETE RESTRICT, payroll_entry_id BIGINT,
    entry_type TEXT NOT NULL CHECK(entry_type IN ('issue','recovery','reversal','adjustment')), amount NUMERIC(14,2) NOT NULL CHECK(amount <> 0),
    reason TEXT NOT NULL, actor_user_id INTEGER REFERENCES users(id) ON DELETE SET NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
  );

  CREATE TABLE IF NOT EXISTS payroll_periods (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, shop_id INTEGER NOT NULL REFERENCES shops(id) ON DELETE RESTRICT,
    name TEXT NOT NULL, period_start DATE NOT NULL, period_end DATE NOT NULL, pay_date DATE NOT NULL,
    created_by INTEGER REFERENCES users(id) ON DELETE SET NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CHECK(period_end >= period_start), UNIQUE(shop_id,period_start,period_end)
  );
  CREATE INDEX IF NOT EXISTS idx_payroll_periods_shop_date ON payroll_periods(shop_id,period_start DESC,period_end DESC);
  CREATE TABLE IF NOT EXISTS payroll_runs (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, shop_id INTEGER NOT NULL REFERENCES shops(id) ON DELETE RESTRICT,
    payroll_period_id BIGINT NOT NULL REFERENCES payroll_periods(id) ON DELETE RESTRICT,
    attendance_snapshot_id BIGINT NOT NULL REFERENCES attendance_summary_snapshots(id) ON DELETE RESTRICT,
    status TEXT NOT NULL DEFAULT 'draft' CHECK(status IN ('draft','reviewed','approved','finalized','reversed')),
    currency CHAR(3) NOT NULL, rule_version TEXT NOT NULL DEFAULT 'payroll-v1', idempotency_key TEXT NOT NULL,
    created_by INTEGER REFERENCES users(id) ON DELETE SET NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    reviewed_by INTEGER REFERENCES users(id) ON DELETE SET NULL, reviewed_at TIMESTAMPTZ,
    approved_by INTEGER REFERENCES users(id) ON DELETE SET NULL, approved_at TIMESTAMPTZ,
    finalized_by INTEGER REFERENCES users(id) ON DELETE SET NULL, finalized_at TIMESTAMPTZ,
    reversed_by INTEGER REFERENCES users(id) ON DELETE SET NULL, reversed_at TIMESTAMPTZ, reversal_reason TEXT,
    UNIQUE(shop_id,idempotency_key), UNIQUE(shop_id,payroll_period_id,status) DEFERRABLE INITIALLY IMMEDIATE
  );
  CREATE INDEX IF NOT EXISTS idx_payroll_runs_shop_status ON payroll_runs(shop_id,status,created_at DESC);
  CREATE TABLE IF NOT EXISTS payroll_entries (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, payroll_run_id BIGINT NOT NULL REFERENCES payroll_runs(id) ON DELETE RESTRICT,
    shop_id INTEGER NOT NULL REFERENCES shops(id) ON DELETE RESTRICT, staff_profile_id INTEGER NOT NULL REFERENCES staff_profiles(id) ON DELETE RESTRICT,
    salary_config_id BIGINT NOT NULL REFERENCES payroll_salary_configs(id) ON DELETE RESTRICT, employee_id TEXT NOT NULL, staff_name TEXT NOT NULL,
    compensation_type TEXT NOT NULL, currency CHAR(3) NOT NULL, scheduled_days INTEGER NOT NULL, work_minutes INTEGER NOT NULL, overtime_minutes INTEGER NOT NULL,
    gross_amount NUMERIC(14,2) NOT NULL, deduction_amount NUMERIC(14,2) NOT NULL, net_amount NUMERIC(14,2) NOT NULL,
    calculation_json JSONB NOT NULL, UNIQUE(payroll_run_id,staff_profile_id)
  );
  CREATE INDEX IF NOT EXISTS idx_payroll_entries_staff ON payroll_entries(shop_id,staff_profile_id,payroll_run_id);
  ALTER TABLE payroll_advance_ledger DROP CONSTRAINT IF EXISTS payroll_advance_ledger_payroll_entry_id_fkey;
  ALTER TABLE payroll_advance_ledger ADD CONSTRAINT payroll_advance_ledger_payroll_entry_id_fkey FOREIGN KEY(payroll_entry_id) REFERENCES payroll_entries(id) ON DELETE RESTRICT;
  CREATE TABLE IF NOT EXISTS payroll_line_items (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, payroll_entry_id BIGINT NOT NULL REFERENCES payroll_entries(id) ON DELETE RESTRICT,
    shop_id INTEGER NOT NULL REFERENCES shops(id) ON DELETE RESTRICT, line_type TEXT NOT NULL CHECK(line_type IN ('base','allowance','overtime','deduction','advance_recovery','adjustment','reversal')),
    name TEXT NOT NULL, quantity NUMERIC(14,4), rate NUMERIC(14,4), amount NUMERIC(14,2) NOT NULL, source_type TEXT NOT NULL, source_id BIGINT,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
  );
  CREATE INDEX IF NOT EXISTS idx_payroll_lines_entry ON payroll_line_items(payroll_entry_id,id);
  CREATE TABLE IF NOT EXISTS payroll_adjustments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, shop_id INTEGER NOT NULL REFERENCES shops(id) ON DELETE RESTRICT,
    staff_profile_id INTEGER NOT NULL REFERENCES staff_profiles(id) ON DELETE RESTRICT,
    target_period_id BIGINT NOT NULL REFERENCES payroll_periods(id) ON DELETE RESTRICT,
    origin_run_id BIGINT REFERENCES payroll_runs(id) ON DELETE RESTRICT,
    adjustment_type TEXT NOT NULL CHECK(adjustment_type IN ('earning','deduction')), name TEXT NOT NULL,
    currency CHAR(3) NOT NULL, amount NUMERIC(14,2) NOT NULL CHECK(amount > 0), reason TEXT NOT NULL,
    status TEXT NOT NULL DEFAULT 'pending' CHECK(status IN ('pending','applied','reversed')),
    applied_entry_id BIGINT REFERENCES payroll_entries(id) ON DELETE RESTRICT,
    idempotency_key TEXT NOT NULL, created_by INTEGER REFERENCES users(id) ON DELETE SET NULL, created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    applied_at TIMESTAMPTZ, reversed_at TIMESTAMPTZ, UNIQUE(shop_id,idempotency_key)
  );
  CREATE INDEX IF NOT EXISTS idx_payroll_adjustments_period_status ON payroll_adjustments(shop_id,target_period_id,status,staff_profile_id);
  CREATE OR REPLACE FUNCTION protect_payroll_adjustment() RETURNS TRIGGER AS $$
  BEGIN
    IF TG_OP='DELETE' THEN RAISE EXCEPTION 'payroll adjustments cannot be deleted'; END IF;
    IF OLD.shop_id IS DISTINCT FROM NEW.shop_id OR OLD.staff_profile_id IS DISTINCT FROM NEW.staff_profile_id OR OLD.target_period_id IS DISTINCT FROM NEW.target_period_id OR OLD.origin_run_id IS DISTINCT FROM NEW.origin_run_id OR OLD.adjustment_type IS DISTINCT FROM NEW.adjustment_type OR OLD.name IS DISTINCT FROM NEW.name OR OLD.currency IS DISTINCT FROM NEW.currency OR OLD.amount IS DISTINCT FROM NEW.amount OR OLD.reason IS DISTINCT FROM NEW.reason OR OLD.idempotency_key IS DISTINCT FROM NEW.idempotency_key THEN RAISE EXCEPTION 'payroll adjustment financial fields are immutable'; END IF;
    IF NOT ((OLD.status='pending' AND NEW.status='applied') OR (OLD.status='applied' AND NEW.status='reversed') OR OLD.status=NEW.status) THEN RAISE EXCEPTION 'invalid payroll adjustment transition'; END IF;
    RETURN NEW;
  END; $$ LANGUAGE plpgsql;
  DROP TRIGGER IF EXISTS trg_payroll_adjustments_protected ON payroll_adjustments;
  CREATE TRIGGER trg_payroll_adjustments_protected BEFORE UPDATE OR DELETE ON payroll_adjustments FOR EACH ROW EXECUTE FUNCTION protect_payroll_adjustment();
  CREATE TABLE IF NOT EXISTS payroll_payslips (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, payroll_entry_id BIGINT NOT NULL UNIQUE REFERENCES payroll_entries(id) ON DELETE RESTRICT,
    shop_id INTEGER NOT NULL REFERENCES shops(id) ON DELETE RESTRICT, payslip_number TEXT NOT NULL, snapshot_json JSONB NOT NULL,
    issued_at TIMESTAMPTZ NOT NULL DEFAULT NOW(), UNIQUE(shop_id,payslip_number)
  );
  CREATE TABLE IF NOT EXISTS payroll_run_history (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, payroll_run_id BIGINT NOT NULL REFERENCES payroll_runs(id) ON DELETE RESTRICT,
    shop_id INTEGER NOT NULL REFERENCES shops(id) ON DELETE RESTRICT, from_status TEXT, to_status TEXT NOT NULL,
    actor_user_id INTEGER REFERENCES users(id) ON DELETE SET NULL, note TEXT, created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
  );
  CREATE INDEX IF NOT EXISTS idx_payroll_history_run ON payroll_run_history(payroll_run_id,created_at,id);
  CREATE TABLE IF NOT EXISTS payroll_payments (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    shop_id INTEGER NOT NULL REFERENCES shops(id) ON DELETE RESTRICT,
    payroll_entry_id BIGINT NOT NULL REFERENCES payroll_entries(id) ON DELETE RESTRICT,
    amount NUMERIC(14,2) NOT NULL CHECK(amount > 0), currency CHAR(3) NOT NULL,
    payment_method TEXT NOT NULL CHECK(payment_method IN ('cash','bank_transfer','mobile_wallet','cheque','other')),
    payment_reference TEXT, note TEXT NOT NULL, paid_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    paid_by INTEGER REFERENCES users(id) ON DELETE SET NULL, idempotency_key TEXT NOT NULL,
    UNIQUE(shop_id,idempotency_key)
  );
  CREATE INDEX IF NOT EXISTS idx_payroll_payments_entry ON payroll_payments(shop_id,payroll_entry_id,paid_at,id);
  CREATE OR REPLACE FUNCTION reject_payroll_payment_mutation() RETURNS TRIGGER AS $$ BEGIN RAISE EXCEPTION 'payroll payments are immutable'; END; $$ LANGUAGE plpgsql;
  DROP TRIGGER IF EXISTS trg_payroll_payments_immutable ON payroll_payments;
  CREATE TRIGGER trg_payroll_payments_immutable BEFORE UPDATE OR DELETE ON payroll_payments FOR EACH ROW EXECUTE FUNCTION reject_payroll_payment_mutation();
  CREATE TABLE IF NOT EXISTS payroll_monthly_releases (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY, shop_id INTEGER NOT NULL REFERENCES shops(id) ON DELETE RESTRICT,
    staff_profile_id INTEGER NOT NULL REFERENCES staff_profiles(id) ON DELETE RESTRICT, salary_config_id BIGINT NOT NULL REFERENCES payroll_salary_configs(id) ON DELETE RESTRICT,
    salary_month DATE NOT NULL, currency CHAR(3) NOT NULL, current_salary NUMERIC(14,2) NOT NULL,
    deduction_amount NUMERIC(14,2) NOT NULL, released_amount NUMERIC(14,2) NOT NULL CHECK(released_amount >= 0),
    calculation_json JSONB NOT NULL, released_by INTEGER REFERENCES users(id) ON DELETE SET NULL, released_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    UNIQUE(shop_id,staff_profile_id,salary_month)
  );
  CREATE INDEX IF NOT EXISTS idx_payroll_monthly_releases_month ON payroll_monthly_releases(shop_id,salary_month,staff_profile_id);
  CREATE OR REPLACE FUNCTION reject_monthly_release_mutation() RETURNS TRIGGER AS $$ BEGIN RAISE EXCEPTION 'monthly salary releases are immutable'; END; $$ LANGUAGE plpgsql;
  DROP TRIGGER IF EXISTS trg_payroll_monthly_releases_immutable ON payroll_monthly_releases;
  CREATE TRIGGER trg_payroll_monthly_releases_immutable BEFORE UPDATE OR DELETE ON payroll_monthly_releases FOR EACH ROW EXECUTE FUNCTION reject_monthly_release_mutation();
  CREATE OR REPLACE FUNCTION reject_finalized_payroll_mutation() RETURNS TRIGGER AS $$
  BEGIN
    IF EXISTS (SELECT 1 FROM payroll_runs r WHERE r.id=COALESCE(OLD.payroll_run_id, NEW.payroll_run_id) AND r.status IN ('finalized','reversed')) THEN
      RAISE EXCEPTION 'finalized payroll records are immutable';
    END IF;
    RETURN CASE WHEN TG_OP='DELETE' THEN OLD ELSE NEW END;
  END; $$ LANGUAGE plpgsql;
  DROP TRIGGER IF EXISTS trg_payroll_entries_immutable ON payroll_entries;
  CREATE TRIGGER trg_payroll_entries_immutable BEFORE UPDATE OR DELETE ON payroll_entries FOR EACH ROW EXECUTE FUNCTION reject_finalized_payroll_mutation();
  DROP TRIGGER IF EXISTS trg_payroll_lines_immutable ON payroll_line_items;
  CREATE OR REPLACE FUNCTION reject_finalized_payroll_line_mutation() RETURNS TRIGGER AS $$
  BEGIN
    IF EXISTS (SELECT 1 FROM payroll_entries e JOIN payroll_runs r ON r.id=e.payroll_run_id WHERE e.id=OLD.payroll_entry_id AND r.status IN ('finalized','reversed')) THEN
      RAISE EXCEPTION 'finalized payroll records are immutable';
    END IF;
    RETURN CASE WHEN TG_OP='DELETE' THEN OLD ELSE NEW END;
  END; $$ LANGUAGE plpgsql;
  CREATE TRIGGER trg_payroll_lines_immutable BEFORE UPDATE OR DELETE ON payroll_line_items FOR EACH ROW EXECUTE FUNCTION reject_finalized_payroll_line_mutation();
  CREATE OR REPLACE FUNCTION reject_payroll_payslip_mutation() RETURNS TRIGGER AS $$ BEGIN RAISE EXCEPTION 'payslips are immutable'; END; $$ LANGUAGE plpgsql;
  DROP TRIGGER IF EXISTS trg_payroll_payslips_immutable ON payroll_payslips;
  CREATE TRIGGER trg_payroll_payslips_immutable BEFORE UPDATE OR DELETE ON payroll_payslips FOR EACH ROW EXECUTE FUNCTION reject_payroll_payslip_mutation();
  CREATE OR REPLACE FUNCTION reject_payroll_ledger_mutation() RETURNS TRIGGER AS $$ BEGIN RAISE EXCEPTION 'advance ledger entries are immutable'; END; $$ LANGUAGE plpgsql;
  DROP TRIGGER IF EXISTS trg_payroll_advance_ledger_immutable ON payroll_advance_ledger;
  CREATE TRIGGER trg_payroll_advance_ledger_immutable BEFORE UPDATE OR DELETE ON payroll_advance_ledger FOR EACH ROW EXECUTE FUNCTION reject_payroll_ledger_mutation();
`;
async function ensurePayrollSchema(executeQuery) { await executeQuery(PAYROLL_MIGRATION_SQL); }
module.exports = { PAYROLL_MIGRATION_SQL, ensurePayrollSchema };
